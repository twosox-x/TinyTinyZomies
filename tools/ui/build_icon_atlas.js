// Rebuilds assets/ui/icons.png + assets/ui/icons.txt from docs/ui_preview/icons.js (game-icons.net, CC BY 3.0).
// White silhouettes on transparent, CELL px per icon, COLS per row; the HUD tints them at draw time.
// Usage (needs Node + Playwright with Chromium): node tools/ui/build_icon_atlas.js
const fs = require('fs'), path = require('path'), { chromium } = require('playwright');
const CELL = 96, PAD = 3, COLS = 16;
const root = path.resolve(__dirname, '../..');
const src = fs.readFileSync(path.join(root, 'docs/ui_preview/icons.js'), 'utf8');
const GI = JSON.parse(src.slice(src.indexOf('window.GI=') + 10).trim().replace(/;$/, ''));
const names = Object.keys(GI).sort();
(async () => {
  const b = await chromium.launch(); const p = await b.newPage();
  const png = await p.evaluate(async ({ GI, names, CELL, PAD, COLS }) => {
    const rows = Math.ceil(names.length / COLS), c = document.createElement('canvas');
    c.width = COLS * CELL; c.height = rows * CELL; const g = c.getContext('2d');
    for (let i = 0; i < names.length; i++) {
      const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${CELL - 2 * PAD}" height="${CELL - 2 * PAD}" viewBox="0 0 512 512" style="color:#fff">${GI[names[i]]}</svg>`;
      const img = new Image(); img.src = 'data:image/svg+xml;base64,' + btoa(unescape(encodeURIComponent(svg)));
      await img.decode();
      g.drawImage(img, (i % COLS) * CELL + PAD, Math.floor(i / COLS) * CELL + PAD);
    }
    return c.toDataURL('image/png');
  }, { GI, names, CELL, PAD, COLS });
  fs.writeFileSync(path.join(root, 'assets/ui/icons.png'), Buffer.from(png.split(',')[1], 'base64'));
  fs.writeFileSync(path.join(root, 'assets/ui/icons.txt'),
    `# game-icons.net (Lorc, Delapouite and contributors), CC BY 3.0. Generated by tools/ui/build_icon_atlas.js\n# cell ${CELL} cols ${COLS} count ${names.length}\n` + names.map((n, i) => `${i} ${n}`).join('\n') + '\n');
  console.log('icons', names.length); await b.close();
})();
